bool buf_has(uint8_t* buf, size_t buf_len, const char* needle, size_t needle_len) {
    if ((needle_len > buf_len)) {
        return false;
    }
    size_t start = 0;
    while (((start + needle_len) <= buf_len)) {
        size_t k = 0;
        size_t diff = 0;
        while ((k < needle_len)) {
            if ((buf[(start + k)] != needle[k])) {
                diff += 1;
            }
            k += 1;
        }
        if ((diff == 0)) {
            return true;
        }
        start += 1;
    }
    return false;
}

uint8_t digit_byte(uint32_t d) {
    uint8_t b = '0';
    if ((d == 1)) {
        b = '1';
    }
    if ((d == 2)) {
        b = '2';
    }
    if ((d == 3)) {
        b = '3';
    }
    if ((d == 4)) {
        b = '4';
    }
    if ((d == 5)) {
        b = '5';
    }
    if ((d == 6)) {
        b = '6';
    }
    if ((d == 7)) {
        b = '7';
    }
    if ((d == 8)) {
        b = '8';
    }
    if ((d == 9)) {
        b = '9';
    }
    return b;
}

size_t put_count(uint8_t* dst, size_t cap, size_t w, uint32_t v) {
    uint8_t tmp[16] = {0};
    size_t n = 0;
    uint32_t x = v;
    if ((x == 0)) {
        tmp[0] = digit_byte(0);
        n = 1;
    }
    while ((x > 0)) {
        tmp[n] = digit_byte((x % 10));
        n += 1;
        x = (x / 10);
    }
    size_t k = 0;
    while ((k < n)) {
        if (((w + k) < cap)) {
            dst[(w + k)] = tmp[((n - 1) - k)];
        }
        k += 1;
    }
    return (w + n);
}

size_t put_str(uint8_t* dst, size_t cap, size_t w, const char* s, size_t s_len) {
    size_t i = 0;
    while ((i < s_len)) {
        if (((w + i) < cap)) {
            dst[(w + i)] = s[i];
        }
        i += 1;
    }
    return (w + s_len);
}

bool str_eq(const char* a, size_t alen, const char* b, size_t blen) {
    if ((alen != blen)) {
        return false;
    }
    size_t diff = 0;
    size_t i = 0;
    while ((i < alen)) {
        if ((a[i] != b[i])) {
            diff += 1;
        }
        i += 1;
    }
    return (diff == 0);
}

bool fmt_accept(uint8_t* src, size_t n, uint8_t* out, size_t m, size_t cap) {
    if ((m > cap)) {
        return false;
    }
    return fmt_exact(src, n, out, m);
}

bool fmt_exact(uint8_t* a, size_t an, uint8_t* b, size_t bn) {
    size_t i = next_solid(a, an, 0);
    size_t j = next_solid(b, bn, 0);
    while (((i < an) && (j < bn))) {
        if ((a[i] != b[j])) {
            return false;
        }
        i = next_solid(a, an, (i + 1));
        j = next_solid(b, bn, (j + 1));
    }
    return ((i >= an) && (j >= bn));
}

size_t fmt_source(uint8_t* src, size_t n, uint8_t* out, size_t cap) {
    size_t w = 0;
    size_t pending = 0;
    size_t ls = 0;
    while ((ls < n)) {
        size_t le = line_stop(src, n, ls);
        size_t ee = trim_end(src, ls, le);
        if ((ee == ls)) {
            pending += 1;
        } else {
            while ((pending > 0)) {
                w = put_byte(out, cap, w, '\n');
                pending -= 1;
            }
            size_t i = ls;
            while (((i < ee) && ((src[i] == ' ') || (src[i] == '\t')))) {
                if ((src[i] == '\t')) {
                    w = put_byte(out, cap, w, ' ');
                    w = put_byte(out, cap, w, ' ');
                    w = put_byte(out, cap, w, ' ');
                    w = put_byte(out, cap, w, ' ');
                } else {
                    w = put_byte(out, cap, w, ' ');
                }
                i += 1;
            }
            while ((i < ee)) {
                w = put_byte(out, cap, w, src[i]);
                i += 1;
            }
            w = put_byte(out, cap, w, '\n');
        }
        ls = (le + 1);
    }
    return w;
}

bool is_space(uint8_t b) {
    return ((((b == ' ') || (b == '\t')) || (b == '\n')) || (b == 13));
}

size_t line_stop(uint8_t* src, size_t n, size_t s) {
    size_t i = s;
    while ((i < n)) {
        if ((src[i] == '\n')) {
            return i;
        }
        i += 1;
    }
    return n;
}

size_t next_solid(uint8_t* t, size_t n, size_t p) {
    size_t i = p;
    while ((i < n)) {
        if ((is_space(t[i]) == false)) {
            return i;
        }
        i += 1;
    }
    return n;
}

size_t put_byte(uint8_t* dst, size_t cap, size_t w, uint8_t b) {
    if ((w < cap)) {
        dst[w] = b;
    }
    return (w + 1);
}

size_t trim_end(uint8_t* src, size_t s, size_t e) {
    size_t x = e;
    while ((x > s)) {
        uint8_t b = src[(x - 1)];
        if ((((b != ' ') && (b != '\t')) && (b != 13))) {
            return x;
        }
        x -= 1;
    }
    return x;
}

