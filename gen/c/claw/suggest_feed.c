void test_twenty_five_fixes_post_twenty_and_count_five_over_the_cap(void) {
    uint8_t inp[4096] = {0};
    uint8_t out[16384] = {0};
    uint32_t st[9] = {0};
    size_t w = put_str(&inp, 4096, 0, "S\t0123456789abcdef0123456789abcdef01234567\n", 43);
    w = put_str(&inp, 4096, w, "F\tspecs/x.t27\t200\n", 18);
    for (size_t k = 0; k < 25; k++) {
        assert((k < 25));
        w = put_str(&inp, 4096, w, "a;  \nb;\n", 8);
    }
    w = put_str(&inp, 4096, w, "H\t@@ -1,50 +1,50 @@\n", 20);
    size_t m = suggest_review(&inp, w, &out, 16384, &st);
    assert((m > 0));
    assert((m <= 16384));
    assert((st[0] == 20));
    assert((st[2] == 5));
}

void test_an_output_buffer_that_is_too_small_is_reported_by_its_size(void) {
    uint8_t inp[512] = {0};
    size_t w = put_str(&inp, 512, 0, "S\t0123456789abcdef0123456789abcdef01234567\n", 43);
    w = put_str(&inp, 512, w, "F\tspecs/x.t27\t16\n", 17);
    w = put_str(&inp, 512, w, "a = 1;  \nb = 2;\n", 16);
    w = put_str(&inp, 512, w, "H\t@@ -1,2 +1,2 @@\n", 18);
    uint8_t out[32] = {0};
    uint32_t st[9] = {0};
    size_t need = suggest_review(&inp, w, &out, 32, &st);
    assert((need > 32));
}


