void test_batch_reads_numbers_until_the_first_non_number(void) {
    uint32_t out[8] = {0};
    assert((batch_numbers("@tri-claw batch 12 345, #6,7", 28, &out, 8) == 4));
    assert((out[0] == 12));
    assert((out[1] == 345));
    assert((out[2] == 6));
    assert((out[3] == 7));
    assert((batch_numbers("@tri-claw batch #10406 30,100", 29, &out, 8) == 3));
    assert((out[0] == 10406));
    assert((out[1] == 30));
    assert((out[2] == 100));
    assert((batch_numbers("@tri-claw batch 5 please 9", 26, &out, 8) == 1));
    assert((out[0] == 5));
    assert((batch_numbers("@tri-claw batch 5\n9", 19, &out, 8) == 1));
    uint8_t t[20] = {0};
    const char* head = "@tri-claw batch 5 9";
    size_t w = 0;
    while ((w < 19)) {
        t[w] = head[w];
        w += 1;
    }
    t[17] = 13;
    assert((batch_numbers(&t, 19, &out, 8) == 1));
    assert((out[0] == 5));
    t[16] = 13;
    assert((batch_numbers(&t, 19, &out, 8) == 0));
    assert((batch_numbers("@tri-claw batch 0 4", 19, &out, 8) == 0));
    assert((batch_numbers("@tri-claw batch # 4", 19, &out, 8) == 0));
    assert((batch_numbers("@tri-claw batch 4x 5", 20, &out, 8) == 0));
    assert((batch_numbers("@tri-claw batch 1234567890", 26, &out, 8) == 0));
    assert((batch_numbers("@tri-claw batch 123456789", 25, &out, 8) == 1));
    assert((out[0] == 123456789));
    assert((batch_numbers("@tri-claw batch", 15, &out, 8) == 0));
    assert((batch_numbers("@tri-claw batch 8 , ", 20, &out, 8) == 1));
    assert((batch_numbers("@tri-claw land 12", 17, &out, 8) == 0));
    assert((batch_numbers("batch 12", 8, &out, 8) == 0));
    assert((batch_numbers("@tri-claw batch 1 2 3 4", 23, &out, 3) == 3));
    assert((out[2] == 3));
}

void test_batch_reads_at_most_a_hundred_numbers(void) {
    uint8_t t[256] = {0};
    const char* head = "@tri-claw batch";
    size_t w = 0;
    while ((w < 15)) {
        t[w] = head[w];
        w += 1;
    }
    size_t k = 0;
    while ((k < 101)) {
        t[w] = ' ';
        t[(w + 1)] = '7';
        w += 2;
        k += 1;
    }
    uint32_t out[128] = {0};
    assert((batch_numbers(&t, w, &out, 128) == BATCH_MAX));
    assert((out[99] == 7));
    assert((batch_numbers(&t, (w - 2), &out, 128) == BATCH_MAX));
    assert((batch_numbers(&t, (w - 4), &out, 128) == 99));
}


