bool is_superseded(uint8_t* raw, size_t n, size_t self_s, size_t* f) {
    if (is_dash(raw, f[2], f[3])) {
        return false;
    }
    size_t g[8] = {0};
    uint32_t rows = 0;
    size_t ls = 0;
    while ((ls < n)) {
        size_t le = qc_line_end(raw, n, ls);
        if ((le > ls)) {
            if ((((ls != self_s) && (rows < CHECK_MAX_ROWS)) && qc_split(raw, ls, le, &g, 4))) {
                if ((row_ok(raw, &g) && (is_dash(raw, g[2], g[3]) == false))) {
                    if ((qc_range_eq(raw, g[0], g[1], f[0], f[1]) && run_gt(raw, g[2], g[3], f[2], f[3]))) {
                        return true;
                    }
                }
            }
            rows += 1;
        }
        ls = (le + 1);
    }
    return false;
}

uint32_t latest_counts(uint8_t* raw, size_t n, uint32_t* st) {
    size_t f[8] = {0};
    size_t c[4] = {0};
    size_t k = 0;
    while ((k < 5)) {
        st[k] = 0;
        k += 1;
    }
    uint32_t rows = 0;
    size_t ls = 0;
    while ((ls < n)) {
        size_t le = qc_line_end(raw, n, ls);
        if ((le > ls)) {
            uint8_t d = K_BAD;
            bool live = true;
            if (((rows < CHECK_MAX_ROWS) && qc_split(raw, ls, le, &f, 4))) {
                if (row_ok(raw, &f)) {
                    if (is_superseded(raw, n, ls, &f)) {
                        live = false;
                    } else {
                        c[0] = f[4];
                        c[1] = f[5];
                        c[2] = f[6];
                        c[3] = f[7];
                        d = check_class(raw, &c);
                    }
                }
            }
            if (live) {
                st[d] += 1;
            } else {
                st[K_SUPERSEDED] += 1;
            }
            rows += 1;
        }
        ls = (le + 1);
    }
    return rows;
}

bool row_ok(uint8_t* raw, size_t* f) {
    if ((f[1] == f[0])) {
        return false;
    }
    bool ctx = qc_range_is(raw, f[4], f[5], ST_CONTEXT, 7);
    if (is_dash(raw, f[2], f[3])) {
        return ctx;
    }
    if (ctx) {
        return false;
    }
    return run_ok(raw, f[2], f[3]);
}

bool run_gt(uint8_t* raw, size_t a, size_t ae, size_t b, size_t be) {
    if (((ae - a) != (be - b))) {
        return ((ae - a) > (be - b));
    }
    size_t i = 0;
    while (((a + i) < ae)) {
        if ((raw[(a + i)] != raw[(b + i)])) {
            return (raw[(a + i)] > raw[(b + i)]);
        }
        i += 1;
    }
    return false;
}

bool run_ok(uint8_t* raw, size_t s, size_t e) {
    if (((e <= s) || ((e - s) > MAX_RUN_DIGITS))) {
        return false;
    }
    if ((raw[s] == '0')) {
        return false;
    }
    size_t i = s;
    while ((i < e)) {
        if (((raw[i] < '0') || (raw[i] > '9'))) {
            return false;
        }
        i += 1;
    }
    return true;
}

uint8_t check_class(uint8_t* raw, size_t* f) {
    size_t s0 = f[0];
    size_t s1 = f[1];
    size_t c0 = f[2];
    size_t c1 = f[3];
    if (qc_range_is(raw, s0, s1, ST_CONTEXT, 7)) {
        if (qc_range_is(raw, c0, c1, "SUCCESS", 7)) {
            return K_PASS;
        }
        if ((qc_range_is(raw, c0, c1, "FAILURE", 7) || qc_range_is(raw, c0, c1, "ERROR", 5))) {
            return K_FAIL;
        }
        if ((qc_range_is(raw, c0, c1, "PENDING", 7) || qc_range_is(raw, c0, c1, "EXPECTED", 8))) {
            return K_WAIT;
        }
        return K_BAD;
    }
    if (qc_range_is(raw, s0, s1, ST_COMPLETED, 9)) {
        if (is_pass_conclusion(raw, c0, c1)) {
            return K_PASS;
        }
        if (is_fail_conclusion(raw, c0, c1)) {
            return K_FAIL;
        }
        return K_BAD;
    }
    if (is_wait_status(raw, s0, s1)) {
        if (qc_range_is(raw, c0, c1, NO_CONCLUSION, 1)) {
            return K_WAIT;
        }
        return K_BAD;
    }
    return K_BAD;
}

bool is_fail_conclusion(uint8_t* raw, size_t s, size_t e) {
    return (((((qc_range_is(raw, s, e, "FAILURE", 7) || qc_range_is(raw, s, e, "CANCELLED", 9)) || qc_range_is(raw, s, e, "TIMED_OUT", 9)) || qc_range_is(raw, s, e, "ACTION_REQUIRED", 15)) || qc_range_is(raw, s, e, "STARTUP_FAILURE", 15)) || qc_range_is(raw, s, e, "STALE", 5));
}

bool is_pass_conclusion(uint8_t* raw, size_t s, size_t e) {
    return ((qc_range_is(raw, s, e, "SUCCESS", 7) || qc_range_is(raw, s, e, "SKIPPED", 7)) || qc_range_is(raw, s, e, "NEUTRAL", 7));
}

bool is_wait_status(uint8_t* raw, size_t s, size_t e) {
    return ((((qc_range_is(raw, s, e, "QUEUED", 6) || qc_range_is(raw, s, e, "IN_PROGRESS", 11)) || qc_range_is(raw, s, e, "WAITING", 7)) || qc_range_is(raw, s, e, "PENDING", 7)) || qc_range_is(raw, s, e, "REQUESTED", 9));
}

