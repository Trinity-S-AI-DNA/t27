size_t mj_put_reason(uint8_t* out, size_t cap, size_t w, uint8_t d, uint8_t* raw, size_t p, uint8_t why) {
    size_t x = put_str(out, cap, w, J_TEXTS[((size_t)(d))], J_LENS[((size_t)(d))]);
    if (((d == J_REQ_RED) || (d == J_LOG))) {
        x = mj_put_name(out, cap, x, raw, p);
        x = put_byte(out, cap, x, '\n');
    }
    if ((d == J_RED)) {
        x = mj_put_name(out, cap, x, raw, p);
        x = put_str(out, cap, x, ": ", 2);
        if ((verdict_of(why) == V_OWN)) {
            x = put_str(out, cap, x, "own: ", 5);
        } else {
            x = put_str(out, cap, x, "unknown: ", 9);
        }
        x = put_str(out, cap, x, WHY_TEXTS[((size_t)(why))], WHY_LENS[((size_t)(why))]);
    }
    return x;
}

size_t merge_plan(uint8_t* raw, size_t n, uint8_t* out, size_t cap) {
    size_t bs[512] = {0};
    size_t be[512] = {0};
    uint8_t dec[512] = {0};
    uint32_t num[512] = {0};
    uint32_t rk[512] = {0};
    size_t dp[512] = {0};
    uint8_t dy[512] = {0};
    size_t sp[512] = {0};
    int32_t ft[512] = {0};
    size_t f[28] = {0};
    size_t det[2] = {0};
    size_t cnt = 0;
    uint32_t extra = 0;
    size_t ls = 0;
    while ((ls < n)) {
        size_t le = qc_line_end(raw, n, ls);
        if ((le > ls)) {
            uint8_t t = mj_tag(raw, ls, le);
            if ((t == 'P')) {
                if ((cnt < MJ_MAX_PRS)) {
                    bs[cnt] = ls;
                    cnt += 1;
                } else {
                    extra += 1;
                }
            } else if ((((((t != 'B') && (t != 'R')) && (t != 'F')) && (t != 'O')) && (cnt == 0))) {
                extra += 1;
            }
        }
        ls = (le + 1);
    }
    size_t i = 0;
    while ((i < cnt)) {
        if (((i + 1) < cnt)) {
            be[i] = bs[(i + 1)];
        } else {
            be[i] = n;
        }
        dec[i] = J_BAD;
        num[i] = 0;
        dp[i] = 0;
        dy[i] = 0;
        sp[i] = 0;
        ft[i] = -1;
        size_t le = qc_line_end(raw, n, bs[i]);
        size_t fe = (bs[i] + 2);
        while (((fe < le) && (raw[fe] != '\t'))) {
            fe += 1;
        }
        int32_t pn = parse_num(raw, (bs[i] + 2), fe);
        if ((pn > 0)) {
            num[i] = ((uint32_t)(pn));
        }
        if (((pn > 0) && qc_split(raw, bs[i], le, &f, MJ_PF))) {
            sp[i] = f[4];
            ft[i] = parse_num(raw, f[26], f[27]);
            dec[i] = mj_judge(raw, n, bs[i], be[i], &f, &det);
            dp[i] = det[0];
            dy[i] = ((uint8_t)(det[1]));
        }
        size_t j = 0;
        while ((j < i)) {
            if (((num[i] != 0) && (num[j] == num[i]))) {
                dec[i] = J_BAD;
            }
            j += 1;
        }
        i += 1;
    }
    i = 0;
    while ((i < cnt)) {
        rk[i] = 0;
        if ((dec[i] == J_MERGE)) {
            size_t j = 0;
            while ((j < cnt)) {
                if (((dec[j] == J_MERGE) && (num[j] < num[i]))) {
                    rk[i] += 1;
                }
                j += 1;
            }
        }
        i += 1;
    }
    i = 0;
    while ((i < cnt)) {
        if (((dec[i] == J_MERGE) && (rk[i] >= MERGE_CAP))) {
            dec[i] = J_CAPPED;
        }
        i += 1;
    }
    size_t w = 0;
    uint32_t r = 0;
    while ((r < MERGE_CAP)) {
        i = 0;
        while ((i < cnt)) {
            if (((dec[i] == J_MERGE) && (rk[i] == r))) {
                w = put_str(out, cap, w, "G\t", 2);
                w = put_count(out, cap, w, num[i]);
                w = put_byte(out, cap, w, '\t');
                w = qc_put_range(out, cap, w, raw, sp[i], (sp[i] + 40));
                w = put_byte(out, cap, w, '\n');
            }
            i += 1;
        }
        r += 1;
    }
    uint32_t st[17] = {0};
    size_t c = 0;
    while ((c < J_COUNT)) {
        st[c] = 0;
        c += 1;
    }
    i = 0;
    while ((i < cnt)) {
        st[((size_t)(dec[i]))] += 1;
        if ((dec[i] != J_MERGE)) {
            w = put_byte(out, cap, w, J_CLASS[((size_t)(dec[i]))]);
            w = put_byte(out, cap, w, '\t');
            if ((num[i] == 0)) {
                w = put_byte(out, cap, w, '-');
            } else {
                w = put_count(out, cap, w, num[i]);
            }
            w = put_byte(out, cap, w, '\t');
            w = mj_put_reason(out, cap, w, dec[i], raw, dp[i], dy[i]);
        }
        i += 1;
    }
    i = 0;
    while ((i < cnt)) {
        if ((dec[i] == J_LOG)) {
            uint8_t rs[16384] = {0};
            size_t pos[128] = {0};
            size_t ln[1] = {0};
            size_t res[3] = {0};
            mj_rows(raw, bs[i], be[i], &rs, MJ_TABLE_CAP, &pos, &ln);
            w = mj_reds(raw, n, &rs, ln[0], &pos, num[i], ft[i], true, out, cap, w, &res);
        }
        i += 1;
    }
    uint32_t bad = (st[((size_t)(J_BAD))] + extra);
    uint32_t waiting = ((((((((st[((size_t)(J_UNKNOWN))] + st[((size_t)(J_CONFLICT))]) + st[((size_t)(J_NO_CLOSE))]) + st[((size_t)(J_UNREAD))]) + st[((size_t)(J_PENDING))]) + st[((size_t)(J_REQ_RED))]) + st[((size_t)(J_REQ_MISSING))]) + st[((size_t)(J_LOG))]) + st[((size_t)(J_QUIET))]);
    w = put_str(out, cap, w, MJ_SUM_HEAD, MJ_SUM_HEAD_LEN);
    w = put_count(out, cap, w, st[((size_t)(J_MERGE))]);
    w = put_str(out, cap, w, MJ_SUM_TEXTS[0], MJ_SUM_LENS[0]);
    w = put_count(out, cap, w, st[((size_t)(J_CAPPED))]);
    w = put_str(out, cap, w, MJ_SUM_TEXTS[1], MJ_SUM_LENS[1]);
    w = put_count(out, cap, w, waiting);
    w = put_str(out, cap, w, MJ_SUM_TEXTS[2], MJ_SUM_LENS[2]);
    w = put_count(out, cap, w, (((st[((size_t)(J_HELD))] + st[((size_t)(J_DRAFT))]) + st[((size_t)(J_BASE))]) + st[((size_t)(J_RED))]));
    w = put_str(out, cap, w, MJ_SUM_TEXTS[3], MJ_SUM_LENS[3]);
    w = put_count(out, cap, w, st[((size_t)(J_BEE))]);
    w = put_str(out, cap, w, MJ_SUM_TEXTS[4], MJ_SUM_LENS[4]);
    w = put_count(out, cap, w, bad);
    w = put_str(out, cap, w, MJ_SUM_TEXTS[5], MJ_SUM_LENS[5]);
    w = put_count(out, cap, w, (((uint32_t)(cnt)) + extra));
    return put_str(out, cap, w, MJ_SUM_TAIL, MJ_SUM_TAIL_LEN);
}

