bool buf_has(uint8_t* buf, size_t buf_len, const char* needle, size_t needle_len) {
    if ((needle_len > buf_len)) {
        return false;
    }
    size_t start = 0;
    while (((start + needle_len) <= buf_len)) {
        size_t k = 0;
        size_t diff = 0;
        while ((k < needle_len)) {
            if ((buf[(start + k)] != needle[k])) {
                diff += 1;
            }
            k += 1;
        }
        if ((diff == 0)) {
            return true;
        }
        start += 1;
    }
    return false;
}

uint8_t digit_byte(uint32_t d) {
    uint8_t b = '0';
    if ((d == 1)) {
        b = '1';
    }
    if ((d == 2)) {
        b = '2';
    }
    if ((d == 3)) {
        b = '3';
    }
    if ((d == 4)) {
        b = '4';
    }
    if ((d == 5)) {
        b = '5';
    }
    if ((d == 6)) {
        b = '6';
    }
    if ((d == 7)) {
        b = '7';
    }
    if ((d == 8)) {
        b = '8';
    }
    if ((d == 9)) {
        b = '9';
    }
    return b;
}

size_t put_count(uint8_t* dst, size_t cap, size_t w, uint32_t v) {
    uint8_t tmp[16] = {0};
    size_t n = 0;
    uint32_t x = v;
    if ((x == 0)) {
        tmp[0] = digit_byte(0);
        n = 1;
    }
    while ((x > 0)) {
        tmp[n] = digit_byte((x % 10));
        n += 1;
        x = (x / 10);
    }
    size_t k = 0;
    while ((k < n)) {
        if (((w + k) < cap)) {
            dst[(w + k)] = tmp[((n - 1) - k)];
        }
        k += 1;
    }
    return (w + n);
}

size_t put_str(uint8_t* dst, size_t cap, size_t w, const char* s, size_t s_len) {
    size_t i = 0;
    while ((i < s_len)) {
        if (((w + i) < cap)) {
            dst[(w + i)] = s[i];
        }
        i += 1;
    }
    return (w + s_len);
}

