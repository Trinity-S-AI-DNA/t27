uint8_t verdict(uint8_t r) {
    if ((r >= DENY_FROM)) {
        return DENY;
    }
    return ALLOW;
}

size_t line_end(uint8_t* buf, size_t s, size_t n) {
    size_t e = s;
    while (((e < n) && (buf[e] != '\n'))) {
        e += 1;
    }
    return e;
}

size_t text_end(uint8_t* buf, size_t s, size_t e) {
    if (((e > s) && (buf[(e - 1)] == '\r'))) {
        return (e - 1);
    }
    return e;
}

bool digest_ok(uint32_t len) {
    return (len == DIGEST_HEX_LEN);
}

uint8_t hot_decision(bool spec_recorded, bool spec_equal, bool exporter_recorded, bool exporter_equal) {
    uint8_t r = part_reason(recorded_part(spec_recorded, spec_equal), REBUILD_SPEC);
    if ((r != REUSE)) {
        return hot_from_reuse(r);
    }
    r = part_reason(recorded_part(exporter_recorded, exporter_equal), REBUILD_TOOLCHAIN);
    return hot_from_reuse(r);
}

uint8_t hot_from_reuse(uint8_t r) {
    if ((r == REUSE)) {
        return HOT_REUSE;
    }
    if ((r == REBUILD_SPEC)) {
        return HOT_REBUILD_SPEC;
    }
    if ((r == REBUILD_TOOLCHAIN)) {
        return HOT_REBUILD_EXPORTER;
    }
    return HOT_MISSING;
}

uint8_t part_reason(uint8_t p, uint8_t diff_reason) {
    if ((p == PART_SAME)) {
        return REUSE;
    }
    if ((p == PART_DIFF)) {
        return diff_reason;
    }
    return REBUILD_MISSING;
}

uint8_t recorded_part(bool recorded, bool equal) {
    if ((recorded == false)) {
        return PART_MISSING;
    }
    if (equal) {
        return PART_SAME;
    }
    return PART_DIFF;
}

