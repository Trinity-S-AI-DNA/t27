_Static_assert(((C_BOUNDARY & C_SCENARIOS) == 0), "invariant: the_checks_are_four_distinct_bits");
_Static_assert(((C_REQUIREMENTS & C_CRITERIA) == 0), "invariant: the_checks_are_four_distinct_bits");
_Static_assert(((C_SCENARIOS & C_REQUIREMENTS) == 0), "invariant: the_checks_are_four_distinct_bits");


