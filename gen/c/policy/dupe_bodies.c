bool same(uint8_t* a, size_t af, size_t at, uint8_t* b, size_t bf, size_t bt) {
    if (((at - af) != (bt - bf))) {
        return false;
    }
    size_t k = 0;
    while (((af + k) < at)) {
        if ((a[(af + k)] != b[(bf + k)])) {
            return false;
        }
        k += 1;
    }
    return true;
}

