uint64_t db_cnt_nth(uint8_t* buf, size_t cs, size_t ce, size_t k) {
    size_t idx = 0;
    uint64_t cur = 0;
    bool has = false;
    size_t i = cs;
    while ((i <= ce)) {
        if (((i == ce) || (buf[i] == ','))) {
            if (has) {
                if ((idx == k)) {
                    return cur;
                }
                idx += 1;
            }
            cur = 0;
            has = false;
        } else {
            if ((cur < 1000000000000)) {
                cur = ((cur * 10) + (uint64_t)((buf[i] - 48)));
            }
            has = true;
        }
        i += 1;
    }
    return 0;
}

