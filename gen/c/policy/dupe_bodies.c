bool db_ent_less(uint32_t* ws, size_t tcap, size_t a, size_t b) {
    if ((ws[a] != ws[b])) {
        return (ws[a] < ws[b]);
    }
    return (ws[(tcap + a)] < ws[(tcap + b)]);
}

bool db_grp_less(uint8_t* buf, uint32_t* ws, size_t tcap, size_t a, size_t b) {
    uint8_t c = db_name_cmp(buf, db_at(ws, (5 * tcap), a), db_at(ws, (6 * tcap), a), db_at(ws, (5 * tcap), b), db_at(ws, (6 * tcap), b));
    if ((c == CMP_LT)) {
        return true;
    }
    if ((c == CMP_GT)) {
        return false;
    }
    return (ws[((7 * tcap) + a)] > ws[((7 * tcap) + b)]);
}

size_t db_sort(uint8_t* buf, uint32_t* ws, size_t tcap, size_t cnt, size_t base, uint8_t kind) {
    size_t i = 0;
    while ((i < cnt)) {
        ws[(base + i)] = ((uint32_t)(i));
        i += 1;
    }
    size_t h = 1;
    while ((h < (cnt / 3))) {
        h = ((3 * h) + 1);
    }
    while ((h >= 1)) {
        size_t k = h;
        while ((k < cnt)) {
            size_t v = db_at(ws, base, k);
            size_t j = k;
            bool moving = true;
            while (moving) {
                moving = false;
                if ((j >= h)) {
                    size_t u = db_at(ws, base, (j - h));
                    bool before = false;
                    if ((kind == 0)) {
                        before = db_ent_less(ws, tcap, v, u);
                    } else {
                        before = db_grp_less(buf, ws, tcap, v, u);
                    }
                    if (before) {
                        ws[(base + j)] = ((uint32_t)(u));
                        j -= h;
                        moving = true;
                    }
                }
            }
            ws[(base + j)] = ((uint32_t)(v));
            k += 1;
        }
        h = (h / 3);
    }
    return cnt;
}

size_t db_groups(uint8_t* buf, uint32_t* ws, size_t tcap, size_t cnt) {
    size_t ng = 0;
    size_t i = 0;
    while ((i < cnt)) {
        size_t first = db_at(ws, (4 * tcap), i);
        size_t j = (i + 1);
        while ((((j < cnt) && (ws[first] == ws[db_at(ws, (4 * tcap), j)])) && (ws[(tcap + first)] == ws[(tcap + db_at(ws, (4 * tcap), j))]))) {
            j += 1;
        }
        if (((j - i) > 1)) {
            size_t best = first;
            size_t k = (i + 1);
            while ((k < j)) {
                size_t e = db_at(ws, (4 * tcap), k);
                if ((db_name_cmp(buf, db_at(ws, (2 * tcap), e), db_at(ws, (3 * tcap), e), db_at(ws, (2 * tcap), best), db_at(ws, (3 * tcap), best)) == CMP_LT)) {
                    best = e;
                }
                k += 1;
            }
            ws[((5 * tcap) + ng)] = ws[((2 * tcap) + best)];
            ws[((6 * tcap) + ng)] = ws[((3 * tcap) + best)];
            ws[((7 * tcap) + ng)] = ((uint32_t)((j - i)));
            ng += 1;
        }
        i = j;
    }
    return ng;
}

