// Verilator-generated top class
Vlamb_labs_top *top;

// Clock period in simulation time units
vluint64_t sim_time = 0;

// -------------------------------------------------------------------------
// Main simulation loop
// -------------------------------------------------------------------------
int main(int argc, char** argv) {
    // Parse command-line arguments
    if (argc > 1) {
        g_test_vec_idx = atoi(argv[1]);
        if (g_test_vec_idx < 0) g_test_vec_idx = 0;
        if (g_test_vec_idx >= g_num_ref_vectors) g_test_vec_idx = g_num_ref_vectors - 1;
    }
    
    printf("=== Verilator testbench for lamb_labs_top ===\n");
    printf("Test vector index: %d (out of %d reference vectors)\n",
           g_test_vec_idx, g_num_ref_vectors);
    
    // Initialize Verilator
    Verilated::commandArgs(argc, argv);
    Verilated::traceEverOn(true);
    
    // Create top instance
    top = new Vlamb_labs_top;
    
    // Set up VCD tracing
    VerilatedVcdC* tfp = new VerilatedVcdC;
    top->trace(tfp, 99);
    tfp->open("lamb_labs_top.vcd");
    
    // -------------------------------------------------------------------------
    // Reset sequence
    // -------------------------------------------------------------------------
    printf("Applying reset...\n");
    top->rst_n = 0;
    top->en = 1;
    top->start = 0;
    // Drive initial A and B values (will be overridden per test vector)
    int i;
    for (i = 0; i < 16; i++) {
        top->A[i] = 0;
        top->B[i] = 0;
    }
    
    // Two cycles of reset
    for (int cyc = 0; cyc < 2; cyc++) {
        top->clk = 0; top->eval(); tfp->dump(sim_time);
        top->clk = 1; top->eval(); tfp->dump(sim_time);
        sim_time++;
    }
    
    top->rst_n = 1;
    
    // -------------------------------------------------------------------------
    // Apply test vector and run simulation
    // -------------------------------------------------------------------------
    const testvec_ref_t *tv = &g_test_vectors[g_test_vec_idx];
    printf("Applying test vector %d:\n", g_test_vec_idx);
    printf("  A = [", 0);
    for (i = 0; i < 15; i++) printf("0x%04x, ", tv->A[i]);
    printf("0x%04x]\\n", tv->A[15]);
    printf("  B = [");
    for (i = 0; i < 15; i++) printf("0x%04x, ", tv->B[i]);
    printf("0x%04x]\\n", tv->B[15]);
    
    // Drive A and B vectors
    for (i = 0; i < 16; i++) {
        top->A[i] = tv->A[i];
        top->B[i] = tv->B[i];
    }
    
    // Pulse start to initiate computation
    top->start = 0;
    // Wait a cycle, then pulse start
    for (int cyc = 0; cyc < 2; cyc++) {
        top->clk = 0; top->eval(); tfp->dump(sim_time);
        top->clk = 1; top->eval(); tfp->dump(sim_time);
        sim_time++;
    }
    
    top->start = 1;
    for (int cyc = 0; cyc < 2; cyc++) {
        top->clk = 0; top->eval(); tfp->dump(sim_time);
        top->clk = 1; top->eval(); tfp->dump(sim_time);
        sim_time++;
    }
    
    top->start = 0;
    
    // -------------------------------------------------------------------------
    // Run simulation: wait for done/result_val, then check UART
    // -------------------------------------------------------------------------
    int max_cycles = TEST_CYCLES;
    int cycle;
    
    printf("Running simulation (max %d cycles)...\n", max_cycles);
    
    for (cycle = 0; cycle < max_cycles; cycle++) {
        top->clk = 0; top->eval(); tfp->dump(sim_time);
        top->clk = 1; top->eval(); tfp->dump(sim_time);
        sim_time++;
        
        // Check if result_val pulses high (valid accumulation)
        if (top->result_val == 1) {
            printf(">>> result_val pulsed HIGH at cycle %d\n", cycle);
            printf("  accum = %d (0x%08x)\n", (int)top->accum, (unsigned)top->accum);
            printf("  uart_tx currently = %d\n", (int)top->uart_tx);
            
            // Compare with expected
            int32_t accum_expected = tv->accum_expected;
            // Note: tv->accum_expected needs to be filled in; for now just print
            printf("  (comparing with expected value from test vector)\n");
            
            // Stop after first result_val pulse
            break;
        }
    }
    
    if (cycle >= max_cycles) {
        printf(">>> WARNING: max cycles reached without result_val pulse\n");
    }
    
    // -------------------------------------------------------------------------
    // Check UART output (uart_tx state)
    // -------------------------------------------------------------------------
    printf("\nUART TX pin behavior:\n");
    printf("  Final uart_tx = %d (1 = idle/high, 0 = active/low)\n", (int)top->uart_tx);
    
    // Run a few more cycles to observe UART
    for (int cyc = 0; cyc < 20; cyc++) {
        top->clk = 0; top->eval(); tfp->dump(sim_time);
        top->clk = 1; top->eval(); tfp->dump(sim_time);
        sim_time++;
        printf("  Cycle %d: uart_tx = %d\n", cyc, (int)top->uart_tx);
    }
    
    // -------------------------------------------------------------------------
    // Check memory of simulation (toggle start, observe behavior)
    // -------------------------------------------------------------------------
    printf("\n>>> Test complete. Exiting.\n");
    
    // Clean up
    tfp->close();
    delete tfp;
    delete top;
    
    return 0;
}